'use strict';

/** נוסח מייל אימות כתובת (תקף 24 שעות). */
function verificationMail(url, { welcome = false } = {}) {
  const intro = welcome ? 'ברוכים הבאים!\n\n' : '';
  return { subject: 'אימות כתובת האימייל בחשבון', text: `${intro}לאימות הכתובת לחצו (בתוקף 24 שעות):\n${url}\n` };
}

/** נוסח מייל איפוס סיסמה (תקף 30 דקות, חד-פעמי). */
function resetMail(url) {
  return {
    subject: 'איפוס סיסמה',
    text: `התקבלה בקשה לאיפוס הסיסמה בחשבון שלכם ב"תלוש בעברית".\n\nלאיפוס לחצו על הקישור (בתוקף 30 דקות, שימוש חד-פעמי):\n${url}\n\nכדי לשמור על ההיסטוריה המוצפנת תצטרכו את מפתח השחזור שקיבלתם בהרשמה. אם אין לכם אותו, אפשר לאפס את הסיסמה אבל ההיסטוריה השמורה תימחק.\n\nאם לא ביקשתם, התעלמו מההודעה. הסיסמה שלכם לא תשתנה.\n`,
  };
}

module.exports = { verificationMail, resetMail };
